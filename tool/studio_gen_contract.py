#!/usr/bin/env python3
"""Generates the Studio data layer from the frozen API contract.

    python tool/studio_gen_contract.py <contract_dir>

<contract_dir> is the folder holding check_fixtures.py and fixtures/ (the
contract's machine-readable source; API_CONTRACT.md sits one level up and is
read only for endpoint parameters). Nothing in the contract folder is changed.

Writes (all under this repo, all marked "GENERATED"):
  lib/src/studio/data/models/studio_enums.dart      every enum, with `unknown`
  lib/src/studio/data/models/studio_models.dart     every shape + Page/Sync classes (freezed)
  lib/src/studio/data/api/studio_api_<group>.dart   one typed mixin per endpoint group
  lib/src/studio/data/fake/studio_fixtures.g.dart   fixtures as one const Map<String, String>
  lib/src/studio/data/fake/studio_endpoint_roles.g.dart  "Who may call" letters per endpoint (the fake filters `actions` by it)
  test/studio/data/generated/*.g.dart               fixture/result tables the tests iterate

After it runs:  dart run build_runner build --delete-conflicting-outputs
(then revert any POS file build_runner touched) and `dart format` the outputs.
"""
import importlib.util
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
if len(sys.argv) < 2:
    sys.exit(__doc__)
CONTRACT = Path(sys.argv[1]).resolve()
sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("check_fixtures", CONTRACT / "check_fixtures.py")
cf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cf)
ENUMS, SHAPES, ENDPOINTS, EXTRA = cf.ENUMS, cf.SHAPES, cf.ENDPOINTS, cf.EXTRA_FIXTURES
FIX = CONTRACT / "fixtures"
MD = (CONTRACT.parent / "API_CONTRACT.md").read_text(encoding="utf-8")

HEADER = "// GENERATED by tool/studio_gen_contract.py from API contract %s. Do not edit.\n// ignore_for_file: type=lint, invalid_annotation_target\n"

RESERVED = set("""abstract as assert async await break case catch class const continue covariant default deferred do dynamic
else enum export extends extension external factory false final finally for Function get hide if implements import in
interface is late library mixin new null of on operator part required rethrow return set show static super switch sync
this throw true try typedef var void while with yield hashCode runtimeType toString copyWith toJson noSuchMethod""".split())

# Contract names that would clash with Flutter, Dio or the existing Studio code.
ENUM_RENAME = {
    "Route": "ProdRoute", "StudioRole": "PersonRole", "Format": "PieceFormat", "Mode": "StudioMode",
    "Platform": "SocialPlatform", "Layer": "ContentLayer", "Stage": "PieceStage", "Level": "NoteLevel",
    "Use": "PieceUse", "Market": "CompMarket", "Tier": "CompTier", "Grade": "RefGrade", "Lang": "StudioLang",
    "Conf": "Confidence", "Remake": "RemakeFit", "Channel": "PostChannel",
}
SHAPE_RENAME = {"Options": "StudioOptions", "Me": "MeProfile", "Page": "PageInfo", "Read": "PostRead",
                "Round": "PaidRound", "Report": "StudioReport", "Rule": "StudioRule", "Media": "StudioMedia",
                "Post": "SocialPost", "Task": "StudioTask", "Person": "StudioPerson", "Drift": "PostDrift",
                "Checks": "PostChecks", "Verdict": "PieceVerdict", "Board": "PieceBoard", "Comment": "StudioComment",
                "Today": "TodayView", "Idea": "StudioIdea", "Ad": "PaidAd", "Shoot": "StudioShoot", "Shot": "ShootShot",
                "Asset": "StudioAsset", "Piece": "StudioPiece", "Version": "PieceVersion", "Decision": "StudioDecision",
                "Moment": "StudioMoment", "Flavour": "StudioFlavour", "Claim": "StudioClaim", "Reference": "StudioReference",
                "Competitor": "StudioCompetitor", "Scorecard": "WeekScorecard", "Actual": "ActualPost", "Problem": "StudioProblem",
                "Ok": "OkResult"}


def camel(s):
    parts = [p for p in re.split(r"[^0-9a-zA-Z]+", s) if p]
    if not parts:
        return "none"
    out = parts[0][0].lower() + parts[0][1:] + "".join(p[0].upper() + p[1:] for p in parts[1:])
    if out[0].isdigit():
        out = "v" + out
    return out


def field_name(s):
    n = camel(s)
    return n + "Value" if n in RESERVED else n


def enum_dart(n):
    return ENUM_RENAME.get(n, n)


def shape_dart(n):
    return SHAPE_RENAME.get(n, n)


def class_of(n):
    return enum_dart(n) if n in ENUMS else shape_dart(n)


def str_lit(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


# ----------------------------------------------------------------------------- types
PAGES = {}  # dart class name -> ("Page"|"Sync", item dart type)


def page_class(kind, inner):
    d = dart_type(inner)
    name = d[0].upper() + d[1:] if d[0].islower() else d
    name = name + ("Page" if kind == "Page" else "Sync")
    PAGES[name] = (kind, d)
    return name


def dart_type(t, with_null=True):
    nullable = t.endswith("?")
    if nullable:
        t = t[:-1]
    m = re.match(r"^(Page|Sync)<(.+)>$", t)
    if m:
        base = page_class(m.group(1), m.group(2))
    elif t.startswith("["):
        base = "List<%s>" % dart_type(t[1:-1])
    elif t.startswith("map["):
        base = "Map<String, %s>" % dart_type(t[4:-1])
    elif t in ENUMS:
        base = enum_dart(t)
    elif t in SHAPES:
        base = shape_dart(t)
    else:
        base = {"str": "String", "id": "String", "int": "int", "float": "double", "bool": "bool", "date": "String",
                "datetime": "String", "time": "String", "json": "dynamic"}[t]
    if nullable and with_null and base != "dynamic":
        base += "?"
    return base


def enum_of(t):
    """The enum behind a (possibly list/map/nullable) type, else None."""
    t = t.rstrip("?")
    if t.startswith("["):
        return enum_of(t[1:-1])
    if t.startswith("map["):
        return enum_of(t[4:-1])
    return t if t in ENUMS else None


# ----------------------------------------------------------------------------- enums
def gen_enums():
    out = [HEADER % "1.0", "import 'package:freezed_annotation/freezed_annotation.dart';\n"]
    for name in sorted(ENUMS, key=enum_dart):
        d = enum_dart(name)
        used, members = set(), []
        for v in ENUMS[name]:
            m = camel(v)
            if m in RESERVED:
                m += "Value"
            while m in used:
                m += "_"
            used.add(m)
            members.append((m, v))
        out.append("/// Contract enum `%s`. `unknown` stands in for a value this app does not know yet.\nenum %s {" % (name, d))
        for m, v in members:
            out.append("  @JsonValue(%s)\n  %s," % (str_lit(v), m))
        out.append("  @JsonValue('__unknown__')\n  unknown;\n")
        out.append("  /// The exact string on the wire.\n  String get wire => switch (this) {")
        for m, v in members:
            out.append("    %s.%s => %s," % (d, m, str_lit(v)))
        out.append("    %s.unknown => '__unknown__',\n  };\n" % d)
        out.append("  /// Parses a wire string; anything not listed becomes `unknown`.\n  static %s parse(String? value) =>\n      %s.values.firstWhere((e) => e.wire == value, orElse: () => %s.unknown);\n}\n" % (d, d, d))
    return "\n".join(out)


# ----------------------------------------------------------------------------- models
def gen_models():
    out = [HEADER % "1.0", "import 'package:freezed_annotation/freezed_annotation.dart';\n",
           "import 'page_like.dart';", "import 'studio_enums.dart';\n",
           "part 'studio_models.freezed.dart';", "part 'studio_models.g.dart';\n"]
    body = []
    for name in SHAPES:
        if name.startswith("Error") or name.startswith("Push"):
            pass  # still generated: tests parse errors.json and push.payloads.json into them
        d = shape_dart(name)
        params = []
        for f, t, note in cf.parse_shape(name):
            fn = field_name(f)
            ann = []
            if fn != f:
                ann.append("name: %s" % str_lit(f))
            e = enum_of(t)
            if e:
                ann.append("unknownEnumValue: %s.unknown" % enum_dart(e))
            a = ("@JsonKey(%s) " % ", ".join(ann)) if ann else ""
            ty = dart_type(t)
            nullable = ty.endswith("?") or ty == "dynamic"
            req = "" if nullable else "required "
            if f == "answer_kind":
                # A row that never stored the kind reads as an option decision (contract v1.2).
                req = "@Default(DecisionKind.option) "
            doc = ("    /// %s\n" % note) if note else ""
            params.append("%s    %s%s%s %s," % (doc, a, req, ty, fn))
        body.append("/// Contract shape `%s`.\n@freezed\nabstract class %s with _$%s {\n  @JsonSerializable(explicitToJson: true)\n  const factory %s({\n%s\n  }) = _%s;\n\n  factory %s.fromJson(Map<String, dynamic> json) =>\n      _$%sFromJson(json);\n}\n"
                    % (name, d, d, d, "\n".join(params), d, d, d))
    # Page / Sync classes (collect after shapes so every use is registered)
    scan = list(ENDPOINTS.values()) + [t for n in SHAPES for _, t, _ in cf.parse_shape(n)]
    for t in scan:
        for m in re.finditer(r"(Page|Sync)<([^>]+)>", t):
            page_class(m.group(1), m.group(2))
    for pname in sorted(PAGES):
        kind, item = PAGES[pname]
        extra = "    required List<String> deleted,\n    required String serverTime,\n" if kind == "Sync" else ""
        extra_json = ""
        body.append("/// `%s<%s>` from the contract (cursor paging%s).\n@freezed\nabstract class %s with _$%s implements PageLike<%s> {\n  @JsonSerializable(explicitToJson: true, fieldRename: FieldRename.snake)\n  const factory %s({\n    required List<%s> items,\n    String? next,\n%s  }) = _%s;\n\n  factory %s.fromJson(Map<String, dynamic> json) =>\n      _$%sFromJson(json);\n}\n"
                    % (kind, item, ", plus deleted ids and server_time" if kind == "Sync" else "", pname, pname, item, pname, item, extra, pname, pname, pname))
    return "\n".join(out) + "\n" + "\n".join(body)


# ----------------------------------------------------------------------------- endpoints
def parse_endpoints():
    s = MD[MD.index("## 3. Endpoints"):MD.index("### 3.18")]
    eps = {}
    for m in re.finditer(r"^#### `([\w.]+)`  \((GET|POST)\)\n(.*?)(?=^#### |^### |\Z)", s, re.S | re.M):
        key, verb, block = m.groups()
        params = []
        for row in re.finditer(r"^\| `(\w+)` \| `([^`]+)` \| (yes)? ?\| ?(.*?) ?\|$", block, re.M):
            params.append((row.group(1), row.group(2), bool(row.group(3)), row.group(4)))
        rm = re.search(r"\*\*Result:\*\* `([^`]+)`", block)
        wm = re.search(r"\*\*Who may call:\*\* (.*)", block)
        letters = "".join(re.findall(r"\b([FLCSVUG]) ", (wm.group(1) if wm else "") + " "))
        eps[key] = {"verb": verb, "params": params, "result": rm.group(1) if rm else None, "who": letters}
    return eps


def result_dart(t):
    return dart_type(t)


def decode_expr(t, var="d"):
    """Dart expression turning the unwrapped JSON `var` into the typed result."""
    if t.startswith("[") and t.endswith("]"):
        inner = t[1:-1]
        return "(%s as List).map((e) => %s).toList()" % (var, decode_expr(inner, "e"))
    cls = dart_type(t)
    return "%s.fromJson(Map<String, dynamic>.from(%s as Map))" % (cls, var)


def dummy(t):
    return {"str": "'x'", "int": "1", "float": "1.0", "bool": "true", "date": "'2026-11-25'",
            "datetime": "'2026-11-25T14:05:00+02:00'", "time": "'09:00'", "json": "<String, dynamic>{}"}[t]


def gen_api(eps):
    groups = {}
    for key in ENDPOINTS:
        g, fn = key.split(".", 1)
        if g == "service":
            continue
        groups.setdefault(g, []).append(fn)
    files = {}
    calls = []  # for the test table
    for g, fns in groups.items():
        cls = "StudioApi" + g[0].upper() + g[1:]
        out = [HEADER % "1.0",
               "import '../models/studio_models.dart';", "import 'studio_api_base.dart';\n",
               "/// Endpoints of the contract group `%s`. Mixed into [StudioApi]; a `[call]` override\n/// (real or fake) is all an implementation needs.\nmixin %s on StudioApiCore {" % (g, cls)]
        for fn in fns:
            key = "%s.%s" % (g, fn)
            ep = eps[key]
            res = ENDPOINTS[key]
            assert ep["result"] == res or ep["result"].replace(" ", "") == res.replace(" ", ""), (key, ep["result"], res)
            mname = camel(g + "_" + fn)
            sig, put, argd = [], [], []
            for pname, ptype, req, meaning in ep["params"]:
                dn = field_name(pname)
                if pname == "request_id":
                    sig.append("String? requestId")
                    put.append("      'request_id': requestId ?? newRequestId(),")
                    continue
                dt = "Object" if ptype == "json" else {"str": "String", "int": "int", "float": "double", "bool": "bool", "date": "String", "datetime": "String", "time": "String", "Lang": "String"}[ptype]
                if req:
                    sig.append("required %s %s" % (dt, dn))
                    put.append("      %s: %s," % (str_lit(pname), dn))
                    argd.append("%s: %s" % (dn, dummy(ptype)))
                elif NULL_CLEARS.search(meaning) or (key, pname) in NULLABLE_EXTRA:
                    # Pass studioClear to send an explicit null (clears the value).
                    sig.append("%s? %s" % (dt, dn))
                    put.append("      if (%s != null) %s: %s == studioClear ? null : %s," % (dn, str_lit(pname), dn, dn))
                else:
                    sig.append("%s? %s" % (dt, dn))
                    put.append("      if (%s != null) %s: %s," % (dn, str_lit(pname), dn))
            doc = "  /// `%s` (%s).%s" % (key, ep["verb"], "" if not ep["params"] else "")
            sigs = "{%s}" % ", ".join(sig) if sig else ""
            ret = result_dart(res)
            dec = decode_expr(res)
            if not sig:
                params_arg = ""
            else:
                params_arg = ", params: {\n%s\n    }" % "\n".join(put)
            get = ", get: true" if ep["verb"] == "GET" else ""
            out.append("%s\n  Future<%s> %s(%s) async {\n    final d = await call(%s%s%s);\n    return %s;\n  }\n"
                       % (doc, ret, mname, sigs, str_lit(studio_prefix + key), params_arg, get, dec))
            calls.append((key, mname, ", ".join(argd)))
        out.append("}\n")
        files["studio_api_%s.dart" % g] = "\n".join(out)
    mixins = ["StudioApi" + g[0].upper() + g[1:] for g in groups]
    base = [HEADER % "1.0"]
    for g in groups:
        base.append("import 'studio_api_%s.dart';" % g)
    base.append("import 'studio_api_base.dart';\n")
    base.append("/// Every typed endpoint call, mixed together. [StudioApi] extends it.\nabstract class StudioApiEndpoints = StudioApiCore with %s;\n" % ", ".join(mixins))
    files["studio_api_endpoints.dart"] = "\n".join(base)
    return files, calls


studio_prefix = "jarz_social.api.studio."

# Parameters that may be cleared with an explicit null. The contract says
# "null clears" in the Meaning column (found by NULL_CLEARS); the table lists
# the ones the contract states only for their sibling: quiet hours are cleared
# as a pair, so quiet_to may be cleared too.
NULL_CLEARS = re.compile(r"null\s+clears", re.I)
NULLABLE_EXTRA = {
    ("settings.set_my_notifications", "quiet_to"),
    # A flavour date is cleared with an explicit null (not stated in the contract).
    ("settings.flavour_set", "available_from"),
    ("settings.flavour_set", "available_to"),
}


# ----------------------------------------------------------------------------- fixtures
def fixture_files():
    return sorted(FIX.glob("*.json"))


def gen_fixtures():
    out = [HEADER % "1.0",
           "/// The contract's sample payloads as raw JSON, keyed by file name without `.json`.\n/// Imported only by the fake API, so normal builds tree-shake it out.\nconst Map<String, String> studioFixtures = {"]
    for f in fixture_files():
        raw = json.dumps(json.loads(f.read_text(encoding="utf-8")), ensure_ascii=False, separators=(",", ":"))
        out.append("  %s: %s," % (str_lit(f.stem), str_lit(raw)))
    out.append("};\n")
    return "\n".join(out)


def gen_roles(eps):
    out = [HEADER % "1.1",
           "/// Who may call each endpoint, as the role letters of the contract's \"Who may call\" lines\n"
           "/// (F Founder, L Marketing Lead, C Creator, S Story Lead, V Service, U Uploader, G guest).\n"
           "/// The fake API filters every object's `actions` by it, so tests and demos show each role only what it may do.\n"
           "const Map<String, String> studioEndpointRoles = {"]
    for k in sorted(eps):
        out.append("  %s: %s," % (str_lit(k), str_lit(eps[k]["who"])))
    out.append("};\n")
    return "\n".join(out)


def gen_test_tables(calls):
    # fixture file -> result type expression for the round-trip test
    rows = []
    for f in fixture_files():
        key = f.stem
        if f.name in EXTRA:
            typ = EXTRA[f.name]
        else:
            base = key if key in ENDPOINTS else ".".join(key.split(".")[:2])
            typ = ENDPOINTS[base]
        rows.append((f.stem, typ))

    def parser(t):
        if t.startswith("map["):
            inner = parser(t[4:-1])
            return "(d) => (d as Map).map((k, v) => MapEntry(k as String, %s(v)))" % inner.join(["(", ")"]) if False else \
                "(d) => (d as Map).map((k, v) => MapEntry(k as String, (%s)(v)))" % inner
        if t.startswith("["):
            return "(d) => (d as List).map((e) => (%s)(e)).toList()" % parser(t[1:-1])
        return "(d) => %s.fromJson(Map<String, dynamic>.from(d as Map))" % dart_type(t)

    def tojson(t):
        # every parsed value goes back to JSON through here
        if t.startswith("map["):
            return "(v) => (v as Map).map((k, e) => MapEntry(k, (%s)(e)))" % tojson(t[4:-1])
        if t.startswith("["):
            return "(v) => (v as List).map((e) => (%s)(e)).toList()" % tojson(t[1:-1])
        return "(v) => (v as dynamic).toJson()"

    out = [HEADER % "1.0",
           "import 'package:jarz_pos/src/studio/data/models/studio_models.dart';\n",
           "/// fixture name -> (parse, toJson). Round-trip table for every contract fixture.\nfinal Map<String, ({Object? Function(Object?) parse, Object? Function(Object?) toJson})> fixtureCodecs = {"]
    for stem, typ in rows:
        out.append("  %s: (parse: %s, toJson: %s)," % (str_lit(stem), parser(typ), tojson(typ)))
    out.append("};\n")
    return "\n".join(out)


def gen_call_table(calls):
    out = [HEADER % "1.0",
           "import 'package:jarz_pos/src/studio/core/network/studio_api.dart';\n",
           "/// endpoint key -> calls the typed method with dummy arguments.\nfinal Map<String, Future<Object?> Function(StudioApi)> endpointCalls = {"]
    for key, m, args in calls:
        out.append("  %s: (api) => api.%s(%s)," % (str_lit(key), m, args))
    out.append("};\n")
    return "\n".join(out)


def write(path, text):
    p = REPO / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path)


def main():
    eps = parse_endpoints()
    missing = [k for k in ENDPOINTS if not k.startswith("service.") and k not in eps]
    assert not missing, missing
    write("lib/src/studio/data/models/studio_enums.dart", gen_enums())
    write("lib/src/studio/data/models/studio_models.dart", gen_models())
    files, calls = gen_api(eps)
    for n, t in files.items():
        write("lib/src/studio/data/api/" + n, t)
    write("lib/src/studio/data/fake/studio_fixtures.g.dart", gen_fixtures())
    write("lib/src/studio/data/fake/studio_endpoint_roles.g.dart", gen_roles(eps))
    write("test/studio/data/generated/fixture_codecs.g.dart", gen_test_tables(calls))
    write("test/studio/data/generated/endpoint_calls.g.dart", gen_call_table(calls))
    print("shapes", len(SHAPES), "enums", len(ENUMS), "pages", len(PAGES), "endpoints", len(calls), "fixtures", len(fixture_files()))


main()
